-- ---------------------------------------------------------------------
-- 共用函式：取代 MySQL 的 ON UPDATE CURRENT_TIMESTAMP
-- ---------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


