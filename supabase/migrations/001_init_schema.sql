-- ---------------------------------------------------------------------
-- 權限：讓前端 supabase-js 可直接新增 / 查詢 / 編輯 / 刪除
-- ⚠ 目前為「先能運作」版本：任何拿到網址 + anon key 的人都能改資料。
--   之後加上登入功能時，把 anon 從政策中拿掉即可（見文末）。
-- ---------------------------------------------------------------------
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on all tables in schema public to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

do $$
declare
  t text;
begin
  foreach t in array array[
    'im_company_defect_reason',
    'im_daily_report',
    'im_daily_report_defect',
    'im_daily_report_shift',
    'im_machine',
    'im_production_number',
    'company_personnel'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format(
      'create policy "allow_all_crud" on public.%I for all to anon, authenticated using (true) with check (true)',
      t
    );
  end loop;
end;
$$;

